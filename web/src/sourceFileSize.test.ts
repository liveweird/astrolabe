/// <reference types="node" />
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * Size guard for every source file under `web/src`: no file may exceed MAX_LINES lines, so a split does not regrow.
 * The twin of the server's `SourceFileSizeTest` (`server/src/test/kotlin/SourceFileSizeTest.kt`), same policy and same
 * wording. Lines are counted exactly like `wc -l` (the number of `\n` characters), so `wc -l <file>` is the number to
 * put in OVERSIZED.
 *
 * Counted: `*.ts` / `*.tsx`. Not counted, each for its own reason:
 * - `*.test.ts(x)` and `src/test/**`: test code and its fixtures are long by nature (describe blocks, tables);
 * - `src/api/schema.ts`: generated by `npm run gen:api`, never edited by hand;
 * - `src/changelog/entries.ts`: release data that grows with every release by design;
 * - `*.d.ts`: ambient declarations.
 *
 * Policy: a NEW file stays at or under MAX_LINES. Today's oversized files are grandfathered in OVERSIZED with their
 * CURRENT size as the ceiling, and the ratchet is exact: a listed file that grew fails, a listed file that SHRANK fails
 * too ("lower the ceiling to N"), a listed file at or under MAX_LINES must be delisted, and a listed file that no longer
 * exists must be delisted. So every ceiling always equals the file's present size and can only go down. Raising a
 * ceiling (or listing a new file) is a deliberate, reviewed exception the PR must justify; the default answer is to
 * split the file by concern first.
 */
const MAX_LINES = 400;
const MIN_FILES = 100;
const NEWLINE = 0x0a;

/** Path under `web/src` -> its line count when the guard was added (a ceiling, never a target). */
const OVERSIZED: Readonly<Record<string, number>> = {};

const SRC_ROOT = dirname(fileURLToPath(import.meta.url));
const EXCLUDED_FILES = new Set(["api/schema.ts", "changelog/entries.ts"]);

function isCounted(path: string): boolean {
  if (!/\.tsx?$/.test(path) || /\.d\.ts$/.test(path) || /\.test\.tsx?$/.test(path)) return false;
  return !path.startsWith("test/") && !EXCLUDED_FILES.has(path);
}

function countNewlines(buffer: Buffer): number {
  let count = 0;
  for (let at = buffer.indexOf(NEWLINE); at !== -1; at = buffer.indexOf(NEWLINE, at + 1)) count += 1;
  return count;
}

function sizes(): Map<string, number> {
  const result = new Map<string, number>();
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) {
        const path = relative(SRC_ROOT, full).split(sep).join("/");
        if (isCounted(path)) result.set(path, countNewlines(readFileSync(full)));
      }
    }
  };
  walk(SRC_ROOT);
  return result;
}

describe("web source file size", () => {
  const measured = sizes();

  it("no source file exceeds the size threshold outside the grandfathered list", () => {
    expect(measured.size, "expected the web sources").toBeGreaterThan(MIN_FILES);
    const tooBig = [...measured]
      .filter(([file, lines]) => lines > (OVERSIZED[file] ?? MAX_LINES))
      .map(([file, lines]) => `${file} has ${lines} lines (limit ${OVERSIZED[file] ?? MAX_LINES})`);
    expect(tooBig, "split these by concern instead of growing them").toEqual([]);
  });

  it("every grandfathered ceiling equals its file's current size", () => {
    const stale = Object.keys(OVERSIZED).filter((file) => (measured.get(file) ?? 0) <= MAX_LINES);
    expect(stale, `delete these entries from OVERSIZED (missing or now <= ${MAX_LINES} lines)`).toEqual([]);
    const loose = Object.entries(OVERSIZED)
      .filter(([file, ceiling]) => (measured.get(file) ?? 0) < ceiling)
      .map(([file, ceiling]) => `${file}: lower the ceiling from ${ceiling} to ${measured.get(file)}`);
    expect(loose, "the ratchet must tighten").toEqual([]);
  });
});
